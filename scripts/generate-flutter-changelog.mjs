import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pubspecPath = path.join(root, 'sdks/flutter/pubspec.yaml');
const notesPath = path.join(root, 'sdks/flutter/release-notes.json');
const changelogPath = path.join(root, 'sdks/flutter/CHANGELOG.md');
const check = process.argv.includes('--check');

function parseVersion(pubspec) {
  const match = pubspec.match(/^version:\s*([^\s#]+)\s*$/m);
  if (!match) throw new Error('Flutter pubspec.yaml has no version');
  return match[1];
}

function semverParts(version) {
  const match = version.match(/^(\d+)\.(\d+)\.(\d+)(?:[-+].*)?$/);
  if (!match) throw new Error(`Unsupported Flutter release version: ${version}`);
  return match.slice(1).map(Number);
}

function compareVersionsDescending(left, right) {
  const a = semverParts(left);
  const b = semverParts(right);
  for (let index = 0; index < a.length; index += 1) {
    if (a[index] !== b[index]) return b[index] - a[index];
  }
  return right.localeCompare(left);
}

function render(notes) {
  const versions = Object.keys(notes).sort(compareVersionsDescending);
  const sections = versions.map((version) => {
    const release = notes[version];
    if (!release || typeof release.date !== 'string' || !Array.isArray(release.notes)) {
      throw new Error(`Invalid Flutter release notes for ${version}`);
    }
    if (release.notes.length === 0 || release.notes.some((note) => typeof note !== 'string' || !note.trim())) {
      throw new Error(`Flutter release ${version} must contain non-empty notes`);
    }
    return [`## ${version} - ${release.date}`, '', ...release.notes.map((note) => `- ${note.trim()}`)].join('\n');
  });

  return [
    '# Changelog',
    '',
    '<!-- Generated by scripts/generate-flutter-changelog.mjs. Do not edit by hand. -->',
    '',
    ...sections.flatMap((section, index) => index === 0 ? [section] : ['', section]),
    '',
  ].join('\n');
}

const [pubspec, notesText] = await Promise.all([
  readFile(pubspecPath, 'utf8'),
  readFile(notesPath, 'utf8'),
]);
const version = parseVersion(pubspec);
const notes = JSON.parse(notesText);
if (!Object.hasOwn(notes, version)) {
  throw new Error(`Flutter release-notes.json has no entry for pubspec version ${version}`);
}
const expected = render(notes);

if (check) {
  const actual = await readFile(changelogPath, 'utf8').catch(() => '');
  if (actual !== expected) {
    throw new Error('Flutter CHANGELOG.md is stale. Run pnpm flutter:changelog:generate.');
  }
  console.log('flutter-changelog: current');
} else {
  await writeFile(changelogPath, expected);
  console.log(`flutter-changelog: wrote ${path.relative(root, changelogPath)}`);
}
