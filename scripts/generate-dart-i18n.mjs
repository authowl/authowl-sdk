/**
 * Generates the Dart message catalogs from `@authowl/core`'s.
 *
 * WHY GENERATE RATHER THAN TRANSLATE TWICE
 *
 * Every user-facing string in this SDK goes through one catalog. That rule is
 * what keeps the Arabic wording on a Flutter screen identical to the Arabic
 * wording on the web, and it is exactly the rule a second hand-maintained Dart
 * catalog would break - silently, and only in the locale nobody on the team
 * reads.
 *
 * Dart cannot import TypeScript, so the strings are emitted instead. The source
 * is the BUILT artifact (`packages/auth-core/dist/messages.js`), not the .ts
 * files: reading the real exported object means the generated catalog cannot
 * drift from what the JavaScript SDK actually ships, and there is no fragile
 * source parsing to get wrong.
 *
 * Usage:
 *   node scripts/generate-dart-i18n.mjs           # write the catalog
 *   node scripts/generate-dart-i18n.mjs --check   # fail if it has drifted
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'packages/auth-core/dist/messages.js');
const OUT = path.join(ROOT, 'sdks/flutter/lib/src/i18n/catalog.g.dart');

/** Dart single-quoted string literal. */
function dartString(value) {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\$/g, '\\$')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r');
  return `'${escaped}'`;
}

let messages;
try {
  messages = await import(path.toNamespacedPath(SOURCE));
} catch {
  console.error(
    'dart-i18n: packages/auth-core/dist/messages.js is missing.\n'
    + 'Run: pnpm --filter @authowl/core run build',
  );
  process.exit(1);
}

const { catalogs } = messages;
const locales = Object.keys(catalogs).sort();
if (locales.length === 0) throw new Error('dart-i18n: no catalogs found');

// Sorted so the output is stable across runs; an unstable generator turns every
// unrelated build into a diff and trains reviewers to ignore it.
const keys = Object.keys(catalogs[locales[0]]).sort();
for (const locale of locales) {
  const missing = keys.filter((key) => !(key in catalogs[locale]));
  if (missing.length > 0) {
    throw new Error(`dart-i18n: locale ${locale} is missing ${missing.length} keys`);
  }
}

const body = locales
  .map((locale) => {
    const entries = keys
      .map((key) => `    ${dartString(key)}: ${dartString(catalogs[locale][key])},`)
      .join('\n');
    return `  ${dartString(locale)}: <String, String>{\n${entries}\n  },`;
  })
  .join('\n');

const serialized = `// GENERATED by scripts/generate-dart-i18n.mjs - do not edit by hand.
//
// The message catalogs, emitted from @authowl/core so the Flutter widgets show
// exactly the wording the JavaScript SDKs show. Regenerate with:
//
//   pnpm --filter @authowl/core run build && node scripts/generate-dart-i18n.mjs
//
// ignore_for_file: lines_longer_than_80_chars
library;

/// Every locale AuthOwl ships, keyed by message id.
const Map<String, Map<String, String>> authOwlCatalogs = <String, Map<String, String>>{
${body}
};

/// The locales with a catalog, in the order they were generated.
const List<String> authOwlLocales = <String>[${locales.map(dartString).join(', ')}];
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = await readFile(OUT, 'utf8');
  } catch {
    console.error('dart-i18n: catalog.g.dart is missing. Run: node scripts/generate-dart-i18n.mjs');
    process.exit(1);
  }
  if (current !== serialized) {
    console.error(
      'dart-i18n: sdks/flutter/lib/src/i18n/catalog.g.dart is stale.\n'
      + 'The shared catalogs changed, so the Flutter widgets are showing different\n'
      + 'wording from the web and React Native ones.\n'
      + 'Run: node scripts/generate-dart-i18n.mjs',
    );
    process.exit(1);
  }
  console.log(`dart-i18n: up to date (${keys.length} keys x ${locales.length} locales).`);
} else {
  await writeFile(OUT, serialized);
  console.log(
    `dart-i18n: wrote ${keys.length} keys x ${locales.length} locales to ${path.relative(ROOT, OUT)}`,
  );
}
