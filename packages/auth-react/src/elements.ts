export type ElementSlot = ELEMENT_SLOTS[number];
export type Elements = Partial<Record<ElementSlot, string>>;
export const ElementsContext = createContext<Elements | undefined>(undefined);

/** Both names ship for one major so existing host selectors keep matching. */
export function slot(name: ElementSlot, elements?: Elements): string {
  return `ao-${name} ba-${name}${elements?.[name] ? ` ${elements[name]}` : ''}`;
}

/** Capture context once, before conditional component returns. */
export function useSlot(): (classes: string) => string {
  const elements = useContext(ElementsContext);
  return (classes) => classes.split(/\s+/).map((name) =>
    name.startsWith('ba-') ? slot(name.slice(3) as ElementSlot, elements) : name,
  ).join(' ');
}
